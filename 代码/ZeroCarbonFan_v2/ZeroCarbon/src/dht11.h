#pragma once
/*
 * 温湿度传感器模块 —— DHT11（YL-47 模块，3 线）
 * ============================================
 * 和 light.h / pm25.h 一个套路：常量 + dht11Init() + dht11Read()。
 *
 * ★ 本模块**用外部库 DHTesp**，不走手写位操作 ★
 *   原因见下方「为什么这里用库，测试程序却手写」。
 *
 * ── 接线 ──────────────────────────────────────
 *   YL-47 模块        ESP32
 *   VCC  (1 脚)  ───→  3.3V        ⚠️ 不是 5V
 *   DATA (2 脚)  ───→  GPIO27
 *   GND  (3 脚)  ───→  GND
 *
 *   **上拉不用自己加** —— YL-47 板上已有 R1 4.7k（手册建议 5k，符合）。
 *   模块上还有电源指示灯 D1，**D1 亮 = 模块通电**。
 *
 *   为什么接 3.3V：手册写 3~5.5V 都行，但 DATA 靠**上拉到 VCC**，
 *   接 5V 则 DATA 高电平 = 5V，而 ESP32 的 GPIO 不是 5V 容限。
 *   （和光敏模块同理；和 PM2.5 转接板相反 —— 那块必须 5V。）
 *
 * ── 引脚：GPIO27 ──────────────────────────────
 *   DHT 是单总线数字信号，不挑 ADC，普通 GPIO 就行。
 *   GPIO27 空闲、非 strapping（0/2/5/12/15）、非 Flash（6~11）、非串口（1/3）。
 *
 * ── 三条硬约束（DHT11 手册要求）───────────────
 *   ① **上电后必须等 1 秒**才能发指令 —— dht11Init() 里 delay(1000)。
 *   ② **采样周期 ≥ 1 秒** —— DHT11 最快约 1 秒一次。本项目用 2 秒。
 *   ③ **本身就是会失败的** —— 见下。
 *
 * ── ⚠️ DHT11 + ESP32 + WiFi 是固有会丢数据的 ────────
 *   DHT11 靠**微秒级时序**区分 0 和 1（低电平结束后 35µs 采样）。
 *   主程序开着 WiFi 热点，**WiFi 中断会打断这个时序**，导致读失败。
 *
 *   **换任何库都只是"少失败一点"，不是"不失败"。** 所以：
 *     · dht11Read() 失败时返回 false，**不修改输出参数**
 *     · main.cpp 的 loop() 里失败就**保留上一次成功的读数**
 *       —— 否则网页上的温湿度会偶尔跳成 0 或乱码
 *     · 采样周期放宽到 2 秒
 *
 *   如果以后觉得成功率还是太低，根治办法是**换 I2C 传感器**
 *   （AHT20 / SHT30）—— 走时钟同步，不怕中断打断，精度还高。
 *
 * ── 为什么这里用库，测试程序却手写 ────────────────
 *   · 本模块（主程序用）：要**稳**、代码要短 → 用 DHTesp
 *   · sensorTest_dht11.cpp（[env:sensor_dht11]）：**手写位操作**
 *     —— 测试程序的用途就是"看清单总线时序到底怎么走"，用库就看不到了
 *   两处各司其职，不是重复实现。
 *
 * ── DHT11 规格（厂商手册）─────────────────────
 *   湿度 20–90 %RH（±5 %RH）｜ 温度 0–50 °C（±2 °C）｜ **分辨力 1**
 *   注意分辨力是 1：温湿度都是**整数，没有小数位** —— 这是正常的，
 *   也是 DHT11 和 DHT22 的主要差别。库返回的是 float，这里四舍五入成整数。
 */

#include <Arduino.h>
#include "DHTesp.h"

// ================== 常量 ==================
const int DHT_PIN = 27;                   // 单总线数据脚
const unsigned long DHT_READ_MS = 2000;   // 采样周期：2 秒（手册要求 ≥1 秒）

// ================== 内部对象 ==================
// 用 static 让它只在本编译单元可见，避免头文件被多处 include 时符号重复
static DHTesp dht;

// ================== 初始化：setup() 里调一次 ==================
inline void dht11Init() {
  dht.setup(DHT_PIN, DHTesp::DHT11);
  // DHT11 手册明文要求：上电后等 1s 越过不稳定状态，期间不要发指令
  delay(1000);
}

// ================== 读取：loop() 里定时调 ==================
// 成功返回 true，把整数温湿度写进 tempOut / humiOut。
// 失败返回 false，**两个输出参数不动** —— 调用方要保留上一次的值。
inline bool dht11Read(int8_t& tempOut, int8_t& humiOut) {
  TempAndHumidity th = dht.getTempAndHumidity();
  if (dht.getStatus() != DHTesp::ERROR_NONE) return false;   // 读失败
  tempOut = (int8_t)round(th.temperature);
  humiOut = (int8_t)round(th.humidity);
  return true;
}
