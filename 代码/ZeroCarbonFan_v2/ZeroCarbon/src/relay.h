#pragma once
/*
 * 继电器模块 —— 4 路，光耦隔离，低电平触发
 * ============================================
 * 和 light.h / pm25.h / dht11.h 一个套路：常量 + relayInit() + relaySet()/relayGet()。
 *
 * ── 接线（⚠️ 跳线帽必须拔掉，这是关键）──────────────
 *   模块         接到
 *   ──────────────────────────────────────
 *   JD-VCC  ───→  5V         只给继电器线圈供电
 *   VCC     ───→  3.3V       只给光耦输入侧供电
 *   GND     ───→  GND        ⚠️ 必须和 ESP32 共地
 *   IN1     ───→  GPIO25
 *   IN2     ───→  GPIO26
 *   IN3     ───→  GPIO27
 *   IN4     ───→  GPIO14
 *
 * ── 为什么必须拔跳线帽 ────────────────────────
 *   跳线帽把 VCC 和 JD-VCC 短接，等于逻辑侧和线圈侧共用 5V。
 *   那样 IN 给高电平时，光耦阳极 5V、ESP32 输出只有 3.3V →
 *   **中间有 1.7V 压差**，光耦可能微导通 → 继电器不完全释放、抖动、发热。
 *
 *   拔掉跳线、VCC 接 3.3V 之后，IN 那一侧参考电压就是 3.3V：
 *     · IN 给 LOW  → 3.3V 对 0V 有压差 → 光耦导通 → 吸合
 *     · IN 给 HIGH → **两端都是 3.3V，压差为 0** → 光耦彻底关断
 *   零压差 = 不抖动不发热。这才是光耦隔离该有的用法。
 *
 * ── 引脚为什么是这四个 ────────────────────────
 *   继电器是**输出设备**，所以：
 *     · 不能用 GPIO 34/35/36/39 —— 它们**只能输入**
 *     · 不能用 GPIO 0/2/5/12/15 —— strapping 脚，上电会误触发
 *     · 不能用 GPIO 6~11（Flash）、1/3（串口）
 *   25 / 26 / 27 / 14 是引脚图上**唯一连续的四个安全输出脚**
 *   （左列第 9~12 孔，上下紧挨着），而且**第 14 孔就是 GND** ——
 *   四根 IN 加一根地从上到下一条线拉过去，不用跳线、不会插错。
 *   （GPIO12 紧跟其后，但它是 strapping 脚，不能占。）
 *
 *   这一组是 2026-09-27 重排过的：原来用 25/26/33/13，四个脚散在板子两头，
 *   接线要横跨半个板子。重排后传感器和继电器在左列排成整齐的一段 ——
 *   引脚分配见 文档/接线与引脚.md。
 *
 * ── 设备分配（对应项目需求）────────────────────
 *   通道 1 → 进风扇 + 排风扇（并联，一起启停）  由 PM2.5 驱动
 *   通道 2 → 灯                                  由光照驱动
 *   通道 3 → 抽湿机（模拟）                      由湿度驱动
 *   通道 4 → 空调（模拟）                        由温度驱动
 *
 * ── 供电提醒 ──────────────────────────────────
 *   4 路**同时吸合**约 4 × 70mA ≈ 280mA（5V）。
 *   用 DC-DC 的 5V 供，**别用电脑 USB 口**（500mA 上限，加 ESP32 自身就满了）。
 */

#include <Arduino.h>

// ================== 常量 ==================
// 通道号用 0~3（数组下标），对外显示时 +1 变成「第 1~4 路」
const int RELAY_PIN[4] = { 25, 26, 27, 14 };
const int RELAY_COUNT  = 4;

const int RELAY_ON_LEVEL  = LOW;    // ★ 低电平触发：给 LOW 才吸合
const int RELAY_OFF_LEVEL = HIGH;

// 通道含义 —— 只用来打日志和填网页，改设备时改这里
const char* const RELAY_NAME[4] = { "进风/排风扇", "灯", "抽湿机", "空调" };

// ================== 初始化：setup() 里调一次 ==================
inline void relayInit() {
  for (int i = 0; i < RELAY_COUNT; i++) {
    // ⚠️ 顺序不能反！必须**先写输出锁存器、再切成输出**。
    //    如果先 pinMode(OUTPUT)，引脚会先输出默认值 LOW ——
    //    而低电平触发意味着 LOW = 吸合，继电器会「咔」地全吸一下。
    //
    //    ESP32 上 digitalWrite() 内部就是 gpio_set_level()，
    //    引脚还是输入模式时它照样写进输出寄存器；之后切到 OUTPUT，
    //    驱动的就是这个已经写好的高电平 → 上电不会误吸合。
    digitalWrite(RELAY_PIN[i], RELAY_OFF_LEVEL);
    pinMode(RELAY_PIN[i], OUTPUT);
  }
}

// ================== 控制 ==================
inline void relaySet(int ch, bool on) {
  if (ch < 0 || ch >= RELAY_COUNT) return;
  digitalWrite(RELAY_PIN[ch], on ? RELAY_ON_LEVEL : RELAY_OFF_LEVEL);
}

// 读**真实**状态：直接读引脚电平，不靠变量记「刚才设成了什么」。
// 这样即使别处改了引脚，读出来的仍是事实，不会骗人。
// （原版固件对风扇就是这么干的，这个思路值得保留。）
inline bool relayGet(int ch) {
  if (ch < 0 || ch >= RELAY_COUNT) return false;
  return digitalRead(RELAY_PIN[ch]) == RELAY_ON_LEVEL;
}
