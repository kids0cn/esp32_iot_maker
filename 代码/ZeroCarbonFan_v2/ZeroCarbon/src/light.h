#pragma once
/*
 * 光照传感器模块 —— GP2Y1014AU · 4 线制 · **只读 AO**
 * ============================================
 * 独立成文件的目的：main.cpp 只负责「装配」（setup / loop / 路由 / 组 JSON），
 * 每个传感器的引脚、阈值、读取逻辑各自收在一个文件里 ——
 * 后面加 PM2.5、继电器、语音时各加一个 .h，**platformio.ini 一行都不用改**
 * （build_src_filter 只筛 .cpp/.ino，管不到头文件）。
 *
 * 模块固定三样东西：常量 + init() + read()。不做接口、不做状态机 —— 教学项目。
 *
 * ── 接线（4 线制模块，但只接三根线）──────────────────
 *   模块 ① VCC → ESP32 **3.3V**   ← 不是 5V！
 *   模块 ② GND → ESP32 GND
 *   模块 ④ AO  → GPIO35          ← 只读输入脚，正适合做 ADC
 *   模块 ③ DO  → **不接**（空着）
 *
 *   为什么 3.3V：模块给 DO 做了 10K 上拉到 VCC，虽不接 DO，
 *   但供电电压就决定了整个模块的逻辑电平；万一以后要用 DO，
 *   接 5V 的话 DO 高电平就是 5V，而 ESP32 GPIO 不是 5V 容限。
 *   LM393 工作电压 2~36V，用 3.3V 供电完全正常。
 *
 *   ⚠️ 接线前核对板子丝印，以实物为准（3 线制只到 DO，少一根 AO）。
 *
 * ── 为什么只用 AO，不用 DO ──────────────────────
 *   1. 省 GPIO —— 只接 AO 就少占一个脚，留给别的模块
 *   2. **没有极性问题** —— AO 高=暗 是分压拓扑决定的
 *      （VCC—[10K]—节点—[光敏电阻]—GND，天暗阻值↑电压↑），
 *      跟 LM393 接同相还是反相无关，不用测、不用猜。
 *      DO 曾因极性判断反过一轮，这里从根上消除。
 *   3. 能给网页**光照强度百分比**，DO 只有亮/暗两态
 *
 *   代价：板上那颗蓝色电位器只影响 DO，这里用不上。
 *         阈值也不在本文件 —— 它在 settings.h，
 *         用户可以在网页上改，改完存进 NVS（断电不丢）。
 *
 * ── GPIO35 的选择理由 ─────────────────────────
 *   只读输入脚（正适合 ADC）、非 strapping（0/2/5/12/15）、
 *   非 Flash（6~11）、非 USB 串口（1/3）。
 *   而且它在引脚图左列第 6 孔，**紧挨着 PM2.5 的 AO（第 7 孔）** ——
 *   两个模拟输入凑成相邻的一条线，接线短、不容易受干扰。
 *   （第 5 孔的 GPIO34 也是只读 ADC1 脚，留空备用。ADC1 那簇
 *     36/39/34/35 **只能输入**，能当输出的只有 32 和 33，那两个归 PM2.5。）
 */

#include <Arduino.h>

// ================== 常量 ==================
const int LIGHT_AO_PIN = 35;     // AO 接哪个脚
// ⚠️ 这里**没有**阈值常量了 —— 判定「暗/亮」的阈值是用户可调的，
//    存在 NVS 里（见 settings.h）。本模块只负责把物理量读出来，
//    「读」和「决策」各管各的：改阈值不会牵动这个模块。

// ================== 初始化：setup() 里调一次 ==================
// INPUT 不是 INPUT_PULLUP —— 模拟输入开上拉会把分压点拽偏，读数就假了。
// 这是**输入模式**，不驱动任何电平，没有烧板子的风险。
inline void lightInit() {
  pinMode(LIGHT_AO_PIN, INPUT);
}

// ================== 读取：拿到读数后调 ==================
// 只返回**光照强度百分比**（0=全暗 ~ 100=很亮），**不做暗/亮判定**。
// 判定阈值由 main 用 settings 里的值算 —— 那是用户能改的，不该写死在这里。
inline void lightRead(int& pct) {
  int raw = analogRead(LIGHT_AO_PIN);       // 0 ~ 4095（3.3V 满量程）
  pct = 100 - (raw * 100L) / 4095;          // AO 高 = 暗 → 取反才是「亮」
  if (pct < 0)   pct = 0;
  if (pct > 100) pct = 100;
}
